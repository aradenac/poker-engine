class CalibrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.calibration = _calibration()
        cls.report = _report()
        cls.sample = _train_sample()

    def test_calibration_is_train_only(self) -> None:
        provenance = self.calibration["provenance"]
        self.assertEqual(provenance["consumed_splits"], ["TRAIN"])
        self.assertFalse(provenance["validation_consumed"])
        self.assertFalse(provenance["test_consumed"])
        self.assertEqual(
            provenance["threshold_calibration"],
            "train_only_hand_grouped_cross_validation",
        )
        self.assertEqual(
            sorted(self.calibration["thresholds"]),
            sorted(
                [
                    "min_feature_share",
                    "min_exact_context_share",
                    "min_model_node_support_per_row",
                    "normalized_entropy",
                    "domain_distance",
                    "extrapolation_margin",
                    "support_floor_share",
                ]
            ),
        )
        self.assertGreater(self.calibration["thresholds"]["min_exact_context_share"], 0.0)
        self.assertGreater(self.calibration["thresholds"]["min_feature_share"], 0.0)
        self.assertGreaterEqual(self.calibration["thresholds"]["normalized_entropy"], 0.0)
        self.assertLessEqual(self.calibration["thresholds"]["normalized_entropy"], 1.0)
        self.assertEqual(
            sorted(self.calibration["category_counts"]), sorted(model.OOD_FEATURE_BLOCKS)
        )
        self.assertIs(self.calibration["exact_context_diagnostic_only"], True)

    def test_calibration_refuses_validation_and_test_rows(self) -> None:
        validation = model.read_dataset_rows(DATASET_PATH, splits=("VALIDATION",))[:8]
        with self.assertRaises(model.GeneralizedResponseModelError):
            model.build_ood_calibration_report(
                self.sample + validation,
                folds=2,
                max_rows=400,
                tuning_max_rows=200,
                architectures=FAST_ARCHITECTURES,
            )
        test = [dict(row, split="TEST") for row in self.sample[:4]]
        with self.assertRaises(model.GeneralizedResponseModelError):
            model.build_ood_calibration_report(
                test, folds=2, max_rows=4, tuning_max_rows=2, architectures=FAST_ARCHITECTURES
            )

    def test_calibration_is_order_independent_and_deterministic(self) -> None:
        first = model.build_ood_calibration_report(
            self.sample,
            folds=2,
            max_rows=800,
            tuning_max_rows=200,
            architectures=FAST_ARCHITECTURES,
        )
        second = model.build_ood_calibration_report(
            list(reversed(self.sample)),
            folds=2,
            max_rows=800,
            tuning_max_rows=200,
            architectures=FAST_ARCHITECTURES,
        )
        self.assertEqual(
            first["calibration"]["canonical_payload_sha256"],
            second["calibration"]["canonical_payload_sha256"],
        )
        self.assertEqual(first["calibration"], second["calibration"])

    def test_thresholds_come_from_out_of_fold_train_evidence(self) -> None:
        report = self.report
        evidence = report["calibration_evidence"]
        protocol = evidence["protocol"]
        self.assertEqual(protocol["kind"], "train_only_hand_grouped_cross_validation")
        self.assertEqual(protocol["consumed_splits"], ["TRAIN"])
        self.assertFalse(protocol["validation_consumed"])
        self.assertFalse(protocol["test_consumed"])
        self.assertGreaterEqual(protocol["folds"], 2)
        self.assertGreater(evidence["records"], 0)
        self.assertTrue(evidence["folds"])
        self.assertTrue(all(set(record) >= {"fold", "fit_rows", "holdout_rows"} for record in evidence["folds"]))
        for key, quantiles in evidence["signal_quantiles"].items():
            self.assertGreater(quantiles["n"], 0, key)
            self.assertLessEqual(quantiles["min"], quantiles["median"], key)
            self.assertLessEqual(quantiles["median"], quantiles["p95"], key)
        thresholds = report["calibration"]["thresholds"]
        self.assertGreaterEqual(
            thresholds["min_exact_context_share"],
            thresholds["support_floor_share"] - 1e-18,
        )
        self.assertGreaterEqual(
            thresholds["min_feature_share"], thresholds["support_floor_share"] - 1e-18
        )

    def test_out_of_fold_evidence_never_abstains_on_absent_in_domain_contexts(self) -> None:
        report = self.report
        oof = report["out_of_fold"]
        self.assertEqual(sum(oof["counts"].values()), oof["n"])
        self.assertEqual(sorted(oof["by_stratum"]), sorted(model.OOD_STRATA))
        absent = oof["exact_context_absent_in_domain"]
