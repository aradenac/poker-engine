#!/usr/bin/env python3
"""#421 guard: frozen OOD / uncertainty gate and its TRAIN-only calibration.

Covers every acceptance criterion of the task:

* the statuses are stable and documented: ``MODEL_SUPPORTED``,
  ``MODEL_SUPPORTED_HIGH_UNCERTAINTY`` and ``MODEL_OOD_ABSTAIN``;
* a never-observed category abstains;
* a sizing / stack extrapolation outside the calibrated TRAIN domain abstains;
* an exact context that was never observed while every single-feature label is
  in-domain is *not* OOD by definition: it may only be high-uncertainty;
* the thresholds are calibrated on TRAIN / cross-validation only;
  ``validation_consumed`` and ``test_consumed`` are false and the calibration
  refuses to consume any other split.

``jsonschema`` is not a declared dependency of this repository, so the contract
is validated with an explicit, reviewable keyword subset, mirroring the
convention of ``tests/preflop/test_generalized_response_model.py``.  The full
TRAIN calibration is regenerated by
``python3 tools/preflop/generalized_response_model.py --ood-calibration-report``;
the guard suite reuses the persisted calibration when it exists and otherwise
calibrates a deterministic stride sample so it stays fast.
"""
from __future__ import annotations

import ast
import contextlib
