import json
import re
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from tools.preflop import generalized_response_model as model  # noqa: E402

MODULE_PATH = ROOT / "tools/preflop/generalized_response_model.py"
CONTRACT_PATH = ROOT / "contracts/training/generalized-response-ood-gate.schema.json"
REPORT_PATH = ROOT / "analysis/issue421_generalized_response/OOD_CALIBRATION_REPORT.json"
DATASET_PATH = ROOT / "analysis/issue421_generalized_response/dataset/GENERALIZED_RESPONSE_DATASET.jsonl"

STATUS_SUPPORTED = model.STATUS_MODEL_SUPPORTED
STATUS_HIGH = model.STATUS_MODEL_SUPPORTED_HIGH_UNCERTAINTY
STATUS_ABSTAIN = model.STATUS_MODEL_OOD_ABSTAIN

#: Fast, deterministic calibration used only when the persisted report is absent.
FAST_FOLDS = 3
FAST_MAX_ROWS = 6000
FAST_TUNING_ROWS = 600
FAST_ARCHITECTURES = (model.ARCH_REGULARIZED,)

_CACHE: dict[str, object] = {}


def _dataset_rows(splits: tuple[str, ...] = ("TRAIN",)) -> list[dict]:
    key = "rows:" + ",".join(splits)
    if key not in _CACHE:
        _CACHE[key] = model.read_dataset_rows(DATASET_PATH, splits=splits)
    return _CACHE[key]  # type: ignore[return-value]


def _report() -> dict:
    """The persisted calibration report when present, else a fast TRAIN-only one."""
    if "report" not in _CACHE:
        if REPORT_PATH.exists():
            _CACHE["report"] = json.loads(REPORT_PATH.read_text(encoding="utf-8"))
            _CACHE["report_source"] = "persisted_report"
        else:
            _CACHE["report"] = model.build_ood_calibration_report(
                _dataset_rows()[::16],
                folds=FAST_FOLDS,
                max_rows=FAST_MAX_ROWS,
                tuning_max_rows=FAST_TUNING_ROWS,
                architectures=FAST_ARCHITECTURES,
            )
            _CACHE["report_source"] = "fast_stride_calibration"
    return _CACHE["report"]  # type: ignore[return-value]


def _calibration() -> dict:
    return _report()["calibration"]


def _candidate() -> dict:
    if "candidate" not in _CACHE:
        # The same deterministic synthetic fixture the sibling model guard uses,
        # so the fitted candidate satisfies the persisted contract.
        rows = model.synthetic_rows(900, 421)
        candidate = model.fit(
            rows, 421, config=model.make_config(tuning_max_rows=250, holdout_modulus=5)
        )
        assert model.validate_candidate(candidate) == [], model.validate_candidate(candidate)
        _CACHE["candidate"] = candidate
    return _CACHE["candidate"]  # type: ignore[return-value]


def _train_sample() -> list[dict]:
    return _dataset_rows()[::16]


def _context(**overrides) -> dict:
    """A real TRAIN context, optionally perturbed."""
    context = dict(_train_sample()[0])
    context.update(overrides)
    return context


def _novel_in_domain_context() -> dict:
    """In-domain by label, never observed as an exact cell."""
    rows = _train_sample()
    calibration = _calibration()
    known = {block: set(counts) for block, counts in calibration["category_counts"].items()}
    support = calibration["exact_context_support"]
    for left in rows[:256]:
        for right in rows[:: max(1, len(rows) // 256)]:
            candidate = dict(left)
            for field in model.OOD_PRICE_AXES:
                candidate[field] = right.get(field)
            candidate["target_total_bb"] = None
            candidate["observed_sizing_bb"] = None
            levels = model.ood_feature_levels(candidate)
            if not all(levels[block] in known[block] for block in model.OOD_FEATURE_BLOCKS):
                continue
            if support.get(model.ood_exact_context_key(candidate), 0) == 0:
                return candidate
    raise AssertionError("no novel in-domain context found in the TRAIN sample")


# ---------------------------------------------------------------------------
# minimal, reviewable JSON-Schema subset validator
# ---------------------------------------------------------------------------


def _resolve(schema: dict, root: dict) -> dict:
    while isinstance(schema, dict) and "$ref" in schema:
        node: object = root
        for part in str(schema["$ref"]).lstrip("#/").split("/"):
            node = node[part]  # type: ignore[index]
        schema = node  # type: ignore[assignment]
    return schema


def _type_ok(value: object, expected: str) -> bool:
    if expected == "object":
        return isinstance(value, dict)
    if expected == "array":
        return isinstance(value, list)
    if expected == "string":
        return isinstance(value, str)
    if expected == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if expected == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if expected == "boolean":
        return isinstance(value, bool)
    if expected == "null":
        return value is None
    raise AssertionError(f"unsupported schema type in the reviewable subset: {expected!r}")


def _errors(value: object, schema: dict, root: dict, path: str) -> list[str]:
    schema = _resolve(schema, root)
    if not isinstance(schema, dict):
        return [f"{path}: schema node is not an object"]
    errors: list[str] = []
    if "const" in schema and value != schema["const"]:
        errors.append(f"{path}: expected const {schema['const']!r}, got {value!r}")
    if "enum" in schema and value not in schema["enum"]:
        errors.append(f"{path}: {value!r} is outside {schema['enum']!r}")
    if "oneOf" in schema:
        matches = sum(1 for branch in schema["oneOf"] if not _errors(value, branch, root, path))
        if matches != 1:
            errors.append(f"{path}: matched {matches} oneOf branches")
    expected = schema.get("type")
    if expected is not None and not _type_ok(value, expected):
        errors.append(f"{path}: expected {expected}, got {type(value).__name__}")
        return errors
    if isinstance(value, dict):
        for key in schema.get("required", []):
            if key not in value:
                errors.append(f"{path}: missing required property {key!r}")
        properties = schema.get("properties") or {}
        if schema.get("additionalProperties") is False:
            extra = sorted(set(value) - set(properties))
            if extra:
                errors.append(f"{path}: unexpected properties {extra}")
        for key, sub in properties.items():
            if key in value:
                errors.extend(_errors(value[key], sub, root, f"{path}.{key}"))
    if isinstance(value, list):
        if "minItems" in schema and len(value) < schema["minItems"]:
            errors.append(f"{path}: fewer than {schema['minItems']} items")
        if "maxItems" in schema and len(value) > schema["maxItems"]:
            errors.append(f"{path}: more than {schema['maxItems']} items")
        if "items" in schema:
            for index, item in enumerate(value):
                errors.extend(_errors(item, schema["items"], root, f"{path}[{index}]"))
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if "minimum" in schema and value < schema["minimum"]:
            errors.append(f"{path}: {value} < minimum {schema['minimum']}")
        if "maximum" in schema and value > schema["maximum"]:
            errors.append(f"{path}: {value} > maximum {schema['maximum']}")
    if isinstance(value, str) and "pattern" in schema:
        if not re.match(schema["pattern"], value):
            errors.append(f"{path}: {value!r} does not match {schema['pattern']!r}")
    return errors


def validate_against_contract(value: object, contract: dict) -> None:
    errors = _errors(value, contract, contract, "$")
    if errors:
        raise AssertionError("contract violation:\n" + "\n".join(errors))


