class GateBehaviourTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.calibration = _calibration()
        cls.candidate = _candidate()
        cls.domain = cls.calibration["domain"]

    def _decide(self, context: dict, model_: object = None) -> dict:
        return model.ood_gate_decision(
            self.candidate if model_ is None else model_, context, calibration=self.calibration
        )

    def test_decision_carries_the_machine_readable_status(self) -> None:
        decision = self._decide(_context())
        self.assertEqual(decision["schema"], model.OOD_GATE_SCHEMA)
        self.assertIn(decision["status"], model.OOD_STATUSES)
        self.assertEqual(decision["abstain"], decision["status"] == STATUS_ABSTAIN)
        self.assertEqual(decision["supported"], not decision["abstain"])
        self.assertEqual(decision["high_uncertainty"], decision["status"] == STATUS_HIGH)
        self.assertFalse(decision["validation_consumed"])
        self.assertFalse(decision["test_consumed"])
        self.assertEqual(
            decision["calibration"]["canonical_payload_sha256"],
            self.calibration["canonical_payload_sha256"],
        )
        for key in model.OOD_NUMERIC_AXES:
            self.assertIn(key, decision["signals"]["axes"])
        self.assertIs(decision["signals"]["exact_context"]["decisive"], False)
        self.assertEqual(model.validate_ood_decision(decision), [])

    def test_never_seen_category_abstains(self) -> None:
        for overrides, expected in (
            ({"family": "NEVER_OBSERVED_FAMILY_421"}, "UNSEEN_CATEGORY"),
            ({"actor_position": "ZZ"}, "UNSEEN_CATEGORY"),
            ({"aggressor_position": "YY"}, "UNSEEN_CATEGORY"),
            ({"to_call_bb": 7777.0}, "EXTRAPOLATION_PRICE"),
        ):
            with self.subTest(overrides=overrides):
                decision = self._decide(_context(**overrides))
                self.assertEqual(decision["status"], STATUS_ABSTAIN)
                self.assertTrue(decision["abstain"])
                self.assertIn(expected, decision["reasons"], decision["reasons"])

    def test_capped_count_features_are_absorbed_by_the_model_resolution(self) -> None:
        # The model caps the count features, so an out-of-range count is *not* a
        # never-seen category: it maps onto the shared capped node.
        for overrides in (
            {"raise_level": 99},
            {"limper_count": 99},
            {"caller_count": 99},
            {"live_positions": ["LJ", "HJ", "CO", "BTN", "SB", "BB"], "table_size": 9},
        ):
            with self.subTest(overrides=overrides):
                decision = self._decide(_context(**overrides))
                self.assertEqual(decision["signals"]["unseen_categories"], {})
                self.assertNotEqual(decision["status"], STATUS_ABSTAIN)

    def test_sizing_extrapolation_abstains(self) -> None:
        ratio_high = float(self.domain[model.OOD_SIZING_AXIS]["trained_max"])
        row = dict(_context())
        row["target_total_bb"] = None
        denominator = float(row["pot_before_bb"]) + float(row["to_call_bb"])
        query = dict(row, target_total_bb=(ratio_high * 2.0 + 10.0) * denominator)
        decision = self._decide(query)
        self.assertEqual(decision["status"], STATUS_ABSTAIN)
        self.assertIn("EXTRAPOLATION_SIZING", decision["reasons"])
        self.assertTrue(decision["signals"]["axes"][model.OOD_SIZING_AXIS]["extrapolation"])

    def test_stack_extrapolation_abstains(self) -> None:
        high = float(self.domain["effective_stack_bb"]["trained_max"])
        low = float(self.domain["effective_stack_bb"]["trained_min"])
        for stack in (high * 2.0 + 10.0, max(low * 0.5, 0.0)):
            with self.subTest(stack=stack):
                decision = self._decide(_context(effective_stack_bb=stack))
                self.assertEqual(decision["status"], STATUS_ABSTAIN)
                self.assertIn("EXTRAPOLATION_STACK", decision["reasons"])

    def test_spline_boundary_inside_domain_is_high_uncertainty_not_abstain(self) -> None:
        knot_max = float(max(model.make_config()["spline_knots"]["effective_stack_bb"]))
        trained_max = float(self.domain["effective_stack_bb"]["trained_max"])
        if trained_max <= knot_max:
            self.skipTest("the calibrated stack domain has no in-domain spline-boundary region")
        decision = self._decide(_context(effective_stack_bb=trained_max))
        self.assertEqual(decision["signals"]["unseen_categories"], {})
        self.assertTrue(decision["signals"]["axes"]["effective_stack_bb"]["spline_boundary"])
        self.assertFalse(decision["signals"]["axes"]["effective_stack_bb"]["extrapolation"])
        self.assertEqual(decision["status"], STATUS_HIGH)

    def test_exact_context_absent_in_domain_is_not_ood(self) -> None:
        novel = _novel_in_domain_context()
        support = self.calibration["exact_context_support"]
        self.assertEqual(support.get(model.ood_exact_context_key(novel), 0), 0)
        decision = self._decide(novel)
        self.assertEqual(decision["signals"]["unseen_categories"], {})
        self.assertEqual(decision["signals"]["exact_context"]["support"], 0)
        self.assertFalse(decision["signals"]["exact_context"]["seen_in_calibration"])
        self.assertIs(decision["signals"]["exact_context"]["decisive"], False)
        self.assertNotEqual(decision["status"], STATUS_ABSTAIN)
        self.assertFalse(decision["abstain"])
        self.assertIn(decision["status"], (STATUS_SUPPORTED, STATUS_HIGH))
        self.assertNotIn(STATUS_ABSTAIN, decision["hard_reasons"])
        # The contrast: the very same context with a never-seen category abstains.
        contrast = self._decide(dict(novel, family="NEVER_OBSERVED_FAMILY_421"))
        self.assertEqual(contrast["status"], STATUS_ABSTAIN)

    def test_exact_context_absence_alone_never_abstains(self) -> None:
        # The exact-context signal is declared non-decisive: a never-observed
        # exact cell can never, on its own, flip the status to ABSTAIN.
        novel = _novel_in_domain_context()
        decision = self._decide(novel)
        hard = set(decision["hard_reasons"])
        self.assertNotIn("LOW_EXACT_CONTEXT_SUPPORT", hard)
        self.assertFalse(any(reason.startswith("EXTRAPOLATION") for reason in hard))
        self.assertNotEqual(decision["status"], STATUS_ABSTAIN)

    def test_gate_without_a_model_never_claims_support(self) -> None:
        decision = model.ood_gate_decision(None, _context(), calibration=self.calibration)
        self.assertIn("PREDICTIVE_UNCERTAINTY_UNAVAILABLE", decision["reasons"])
        self.assertNotEqual(decision["status"], STATUS_SUPPORTED)
        self.assertIsNone(decision["signals"]["predictive_uncertainty"])
        self.assertEqual(model.validate_ood_decision(decision), [])

    def test_response_model_wrapper_exposes_the_gate(self) -> None:
        wrapper = model.ResponseModel(self.candidate)
        decision = wrapper.ood_gate(_context(), calibration=self.calibration)
        self.assertEqual(decision["status"], wrapper.ood_status(_context(), calibration=self.calibration))
        self.assertIn(decision["status"], model.OOD_STATUSES)

    def test_decision_is_deterministic(self) -> None:
        first = self._decide(_context())
        second = self._decide(_context())
        self.assertEqual(first, second)

    def test_missing_domain_axis_fails_closed(self) -> None:
        sparse = {key: value for key, value in _context().items() if key != "pot_before_bb"}
        decision = self._decide(sparse)
        self.assertEqual(decision["status"], STATUS_ABSTAIN)
        self.assertIn("MISSING_DOMAIN_AXIS", decision["reasons"])

    def test_out_of_domain_context_returns_a_decision_instead_of_raising(self) -> None:
        decision = self._decide(
            {
                "family": "TOTALLY_UNKNOWN",
                "actor_position": "ZZ",
                "aggressor_position": "YY",
                "limper_count": 9,
                "caller_count": 9,
                "live_positions": ["BTN"],
                "table_size": 6,
                "raise_level": 42,
                "to_call_bb": 10_000.0,
                "pot_before_bb": 20_000.0,
                "effective_stack_bb": 50_000.0,
            }
        )
        self.assertEqual(decision["status"], STATUS_ABSTAIN)
        self.assertEqual(model.validate_ood_decision(decision), [])

    def test_default_loader_reads_the_persisted_report(self) -> None:
        if not REPORT_PATH.exists():
            self.skipTest("the OOD calibration report has not been generated in this worktree")
        loaded = model.load_ood_calibration()
        decision = model.ood_gate_decision(self.candidate, _context(), calibration=loaded)
        self.assertEqual(model.validate_ood_decision(decision), [])
        self.assertIn(decision["status"], model.OOD_STATUSES)


