class StatusContractTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.calibration = _calibration()
        cls.candidate = _candidate()
        cls.contract = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))

    def test_statuses_are_stable_and_documented(self) -> None:
        self.assertEqual(
            model.OOD_STATUSES,
            ("MODEL_SUPPORTED", "MODEL_SUPPORTED_HIGH_UNCERTAINTY", "MODEL_OOD_ABSTAIN"),
        )
        self.assertEqual(list(model.OOD_STATUS_DEFINITIONS), list(model.OOD_STATUSES))
        for status in model.OOD_STATUSES:
            self.assertTrue(model.OOD_STATUS_DEFINITIONS[status].strip())
        self.assertEqual(model.OOD_GATE_SCHEMA, "poker-generalized-response-ood-gate/v1")
        self.assertEqual(
            model.OOD_CALIBRATION_SCHEMA, "poker-generalized-response-ood-calibration/v1"
        )
        self.assertEqual(
            model.OOD_REPORT_SCHEMA, "poker-generalized-response-ood-calibration-report/v1"
        )
        self.assertTrue(set(model.OOD_HARD_REASONS) <= set(model.OOD_REASON_ORDER))
        self.assertTrue(set(model.OOD_SOFT_REASONS) <= set(model.OOD_REASON_ORDER))
        self.assertFalse(set(model.OOD_HARD_REASONS) & set(model.OOD_SOFT_REASONS))
        self.assertEqual(STATUS_SUPPORTED, "MODEL_SUPPORTED")
        self.assertEqual(STATUS_HIGH, "MODEL_SUPPORTED_HIGH_UNCERTAINTY")
        self.assertEqual(STATUS_ABSTAIN, "MODEL_OOD_ABSTAIN")

    def test_contract_pins_the_gate_surface(self) -> None:
        contract = self.contract
        self.assertEqual(contract["$schema"], "https://json-schema.org/draft/2020-12/schema")
        self.assertEqual(len(contract["oneOf"]), 3)
        self.assertEqual(
            list(contract["$defs"]["status"]["enum"]), list(model.OOD_STATUSES)
        )
        self.assertEqual(
            contract["$defs"]["oodGateDecision"]["properties"]["schema"]["const"],
            model.OOD_GATE_SCHEMA,
        )
        self.assertEqual(
            contract["$defs"]["calibration"]["properties"]["schema"]["const"],
            model.OOD_CALIBRATION_SCHEMA,
        )
        self.assertEqual(
            contract["$defs"]["oodCalibrationReport"]["properties"]["schema"]["const"],
            model.OOD_REPORT_SCHEMA,
        )
        self.assertIs(
            contract["$defs"]["calibration"]["properties"]["exact_context_diagnostic_only"]["const"],
            True,
        )
        self.assertEqual(
            sorted(contract["$defs"]["reasonCode"]["enum"]), sorted(model.OOD_REASON_ORDER)
        )
        self.assertEqual(
            sorted(contract["$defs"]["thresholds"]["required"]),
            sorted(
                [
                    "min_feature_share",
                    "min_exact_context_share",
                    "min_model_node_support_per_row",
                    "normalized_entropy",
                    "domain_distance",
                    "extrapolation_margin",
                ]
            ),
        )

    def test_decision_calibration_and_report_validate_against_the_contract(self) -> None:
        decision = model.ood_gate_decision(
            self.candidate, _context(), calibration=self.calibration
        )
        validate_against_contract(decision, self.contract)
        validate_against_contract(self.calibration, self.contract)
        validate_against_contract(_report(), self.contract)

    def test_module_structural_validators_accept_their_own_output(self) -> None:
        self.assertEqual(model.validate_ood_calibration(self.calibration), [])
        decision = model.ood_gate_decision(self.candidate, _context(), calibration=self.calibration)
        self.assertEqual(model.validate_ood_decision(decision), [])
        tampered = dict(decision)
        tampered["abstain"] = not bool(decision["abstain"])
        self.assertTrue(model.validate_ood_decision(tampered))
        tampered = json.loads(json.dumps(self.calibration))
        tampered["provenance"]["validation_consumed"] = True
        self.assertTrue(model.validate_ood_calibration(tampered))

    def test_module_imports_only_the_standard_library(self) -> None:
        tree = ast.parse(MODULE_PATH.read_text(encoding="utf-8"))
        allowed = {
            "argparse",
            "bisect",
            "hashlib",
            "json",
            "math",
            "sys",
            "pathlib",
            "typing",
            "__future__",
        }
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    self.assertIn(alias.name.split(".")[0], allowed, alias.name)
            elif isinstance(node, ast.ImportFrom) and node.module:
                self.assertIn(node.module.split(".")[0], allowed, node.module)


