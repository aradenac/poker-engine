def _probe_context(**overrides: object) -> dict:
    """A public, in-domain response context of the frozen in-window probe set."""
    context: dict = {
        "family": "UNOPENED",
        "actor_position": "LJ",
        "aggressor_position": None,
        "caller_count": 0,
        "limper_count": 0,
        "raise_level": 0,
        "live_positions": ["LJ", "HJ", "CO", "BTN", "SB", "BB"],
        "table_size": 6,
        "to_call_bb": 1.0,
        "pot_before_bb": 1.5,
        "effective_stack_bb": 70.975,
    }
    context.update(overrides)
    return context


#: ``(probe_id, action, queried target, context overrides)`` of the frozen
#: in-window probe set: both aggressive branches, a derived and a supplied
#: engine window, a limped family and three stack depths.
IN_WINDOW_PROBE_SPECS: tuple[tuple[str, str, float, dict], ...] = (
    ("free_unopened_raise_floor", "RAISE", 2.0, {}),
    ("free_unopened_raise_default_relative", "RAISE", 3.0, {}),
    ("free_unopened_jam_effective_stack", "JAM", 70.975, {}),
    (
        "explicit_interval_raise_interior",
        "RAISE",
        12.0,
        {"min_raise_to_bb": 9.0, "max_raise_to_bb": 60.0},
    ),
    (
        "explicit_interval_jam_cap",
        "JAM",
        60.0,
        {"min_raise_to_bb": 9.0, "max_raise_to_bb": 60.0},
    ),
    (
        "vs_limpers_bb_raise_3bb",
        "RAISE",
        3.0,
        {
            "family": "VS_LIMPERS",
            "actor_position": "BB",
            "limper_count": 1,
            "live_positions": ["BTN", "SB", "BB"],
            "to_call_bb": 0.5,
            "pot_before_bb": 2.5,
        },
    ),
    ("short_stack_raise_15bb", "RAISE", 15.0, {"effective_stack_bb": 20.0}),
    ("short_stack_jam_cap", "JAM", 20.0, {"effective_stack_bb": 20.0}),
    ("deep_stack_raise_9bb", "RAISE", 9.0, {"effective_stack_bb": 150.0}),
)

#: The runtime revision the in-window entries were captured from.  The entries
#: were re-computed bit for bit after the explicit legal-window declaration was
#: added, so this pinned revision stays the capture reference.
CAPTURED_AT_RUNTIME_MODULE_SHA256 = (
    "e390a199857a00357969c51ec87af2b2f5e799384a3aa4858c0762a70411b538"
)


def in_window_probes() -> list[dict]:
    """The frozen in-window probe set, rebuilt deterministically.

    Every probe must query a target the engine window admits; the builder
    asserts that instead of trusting it, so a probe can never drift into the
    out-of-window regime the reference is not meant to describe.
    """
    probes: list[dict] = []
    for probe_id, action, target, overrides in IN_WINDOW_PROBE_SPECS:
        context = _probe_context(**overrides)
        window = model.raise_sizing_window(context, action=action)
        if window["fail_closed"] or not (
            float(window["floor_bb"]) - 1e-9 <= target <= float(window["cap_bb"]) + 1e-9
        ):
            raise AssertionError(
                f"frozen probe {probe_id} queries {target} outside the legal window "
                f"[{window['floor_bb']}, {window['cap_bb']}]"
            )
        probes.append(
            {
                "probe_id": probe_id,
                "action": action,
                "target_total_bb": target,
                "context": dict(context, target_total_bb=target),
            }
        )
    return probes


def in_window_reference_entries() -> list[dict]:
    """Recompute the frozen in-window predictions from the frozen candidate."""
    handle = runtime.GeneralizedResponseRuntime()
    entries: list[dict] = []
    for probe in in_window_probes():
        context, action = probe["context"], probe["action"]
        window = model.raise_sizing_window(context, action=action)
        document = handle.resolve(context, action=action, include_sizing=True)
        prediction = model.predict(handle.candidate, context)
        probabilities = dict(document["action_probabilities"])
        sizing = document["sizing"] or {}
        entries.append(
            {
                "probe_id": probe["probe_id"],
                "action": action,
                "target_total_bb": probe["target_total_bb"],
                "family": context["family"],
                "actor_position": context["actor_position"],
                "effective_stack_bb": context["effective_stack_bb"],
                "legal_window_bb": [window["floor_bb"], window["cap_bb"]],
                "bounds_source": dict(window["bounds_source"]),
                "runtime_status": document["status"],
                "runtime_usable": document["usable"],
                "runtime_selected_action": document["selected_action"],
                "runtime_selected_sizing_bb": document["selected_sizing_bb"],
                "runtime_sizing_status": sizing.get("status"),
                "runtime_generated_sizings_sha256": model.stable_hash(
                    list(sizing.get("generated_sizings_bb") or [])
                ),
                "runtime_probabilities": probabilities,
                "runtime_probability_sum": document["probability_sum"],
                "runtime_illegal_mass": document["illegal_mass"],
                "runtime_inside_legal_window": document["sizing_window"][
                    "inside_legal_window"
                ],
                "runtime_prediction_sha256": model.stable_hash(
                    {
                        "status": document["status"],
                        "usable": document["usable"],
                        "selected_action": document["selected_action"],
                        "selected_sizing_bb": document["selected_sizing_bb"],
                        "probabilities": probabilities,
                        "probability_sum": document["probability_sum"],
                        "illegal_mass": document["illegal_mass"],
                    }
                ),
                "model_probabilities": dict(prediction["probabilities"]),
                "model_prediction_sha256": model.stable_hash(prediction),
            }
        )
    return entries


def build_in_window_reference() -> dict:
    """The frozen in-window reference document, recomputed (never hand-edited)."""
    handle = runtime.GeneralizedResponseRuntime()
    entries = in_window_reference_entries()
    return {
        "schema": REFERENCE_SCHEMA,
        "kind": REFERENCE_KIND,
        "issue": 421,
        "purpose": (
            "Freeze the in-window RAISE/JAM response predictions so that the explicit "
            "legal-window declaration (and any later revision) is proved not to move the "
            "in-window distribution."
        ),
        "rule": (
            "an in-window query keeps the same action distribution and the same selected "
            "sizing as before the legal-window declaration was added; only the declared "
            "sizing_window verdict, never a probability, is new"
        ),
        "candidate_id": handle.entry.get("candidate_id"),
        "candidate_canonical_payload_sha256": handle.candidate["canonical_payload_sha256"],
        "model_module_sha256": model.sha256_bytes(MODULE_PATH.read_bytes()),
        "captured_at_runtime_module_sha256": CAPTURED_AT_RUNTIME_MODULE_SHA256,
        "entries": entries,
        "entries_sha256": model.stable_hash(entries),
        "boundary": {
            "test_consumed": False,
            "validation_split_reopened": False,
            "active_pointer_mutated": False,
            "issue367_executed": False,
        },
        "regeneration": (
            "python3 tests/preflop/test_generalized_response_sizing.py "
            "--write-in-window-reference"
        ),
    }


class InWindowReferenceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        if not REFERENCE_PATH.exists():
            raise AssertionError(
                "the frozen in-window reference is missing: regenerate it with "
                "python3 tests/preflop/test_generalized_response_sizing.py "
                "--write-in-window-reference"
            )
        cls.reference = json.loads(REFERENCE_PATH.read_text(encoding="utf-8"))
        cls.entries = in_window_reference_entries()

    def test_the_reference_is_self_consistent_and_bound_to_the_frozen_candidate(self) -> None:
        reference = self.reference
        self.assertEqual(reference["schema"], REFERENCE_SCHEMA)
        self.assertEqual(reference["kind"], REFERENCE_KIND)
        self.assertGreaterEqual(len(reference["entries"]), 6)
        self.assertEqual(reference["entries_sha256"], model.stable_hash(reference["entries"]))
        self.assertEqual(
            reference["model_module_sha256"], model.sha256_bytes(MODULE_PATH.read_bytes())
        )
        self.assertEqual(
            reference["candidate_canonical_payload_sha256"],
            runtime.GeneralizedResponseRuntime().candidate["canonical_payload_sha256"],
        )
        self.assertEqual(len(CAPTURED_AT_RUNTIME_MODULE_SHA256), 64)
        self.assertEqual(reference["boundary"]["test_consumed"], False)
        self.assertEqual(reference["boundary"]["issue367_executed"], False)

    def test_in_window_predictions_are_bit_for_bit_unchanged(self) -> None:
        pinned = self.reference["entries"]
        self.assertEqual(
            [entry["probe_id"] for entry in pinned],
            [entry["probe_id"] for entry in self.entries],
        )
        for expected, recomputed in zip(pinned, self.entries):
            with self.subTest(probe=expected["probe_id"]):
                # Exact equality of the persisted values and of a fresh recomputation:
                # the floats survive the JSON round trip unchanged, so this is a
                # bit-for-bit comparison, not a tolerance.
                self.assertEqual(
                    json.dumps(recomputed, sort_keys=True),
                    json.dumps(expected, sort_keys=True),
                )
                self.assertEqual(
                    recomputed["runtime_prediction_sha256"], expected["runtime_prediction_sha256"]
                )
                self.assertEqual(
                    recomputed["model_prediction_sha256"], expected["model_prediction_sha256"]
                )
                self.assertEqual(
                    recomputed["runtime_generated_sizings_sha256"],
                    expected["runtime_generated_sizings_sha256"],
                )
                self.assertEqual(
                    recomputed["runtime_selected_sizing_bb"],
                    expected["runtime_selected_sizing_bb"],
                )
                self.assertEqual(
                    set(recomputed["runtime_probabilities"]), set(model.ACTIONS)
                )
                self.assertAlmostEqual(
                    sum(recomputed["runtime_probabilities"].values()), 1.0, places=9
                )

    def test_every_frozen_probe_queries_a_target_inside_its_legal_window(self) -> None:
        for probe in in_window_probes():
            context, action = probe["context"], probe["action"]
            window = model.raise_sizing_window(context, action=action)
            with self.subTest(probe=probe["probe_id"]):
                self.assertFalse(window["fail_closed"])
                self.assertGreaterEqual(
                    probe["target_total_bb"], float(window["floor_bb"]) - 1e-9
                )
                self.assertLessEqual(probe["target_total_bb"], float(window["cap_bb"]) + 1e-9)

    def test_the_declaration_is_inside_for_every_frozen_probe(self) -> None:
        for entry in self.reference["entries"]:
            with self.subTest(probe=entry["probe_id"]):
                self.assertTrue(entry["runtime_inside_legal_window"], entry["probe_id"])
                self.assertTrue(entry["runtime_usable"], entry["probe_id"])


def _write_in_window_reference() -> int:
    document = build_in_window_reference()
    REFERENCE_PATH.write_text(
        json.dumps(document, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(
        json.dumps(
            {
                "status": "WROTE",
                "path": REFERENCE_PATH.relative_to(ROOT).as_posix(),
                "entries": len(document["entries"]),
                "entries_sha256": document["entries_sha256"],
            },
            indent=2,
        )
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv if argv is None else argv)
    if "--write-in-window-reference" in argv:
        argv.remove("--write-in-window-reference")
        return _write_in_window_reference()
    unittest.main(argv=argv)
    return 0


