class SizingTargetWindowDeclarationTests(unittest.TestCase):
    """Both sides of the legal window are declared explicitly by the channel.

    The scoring surface already refuses to re-score an outside target; these
    tests pin that the refusal is *stated* -- ``inside_window=false`` plus the
    stable ``TARGET_OUTSIDE_LEGAL_WINDOW`` reason and no substitution -- for a
    target below the engine minimum raise and for a target beyond the cap.
    """

    @classmethod
    def setUpClass(cls) -> None:
        cls.channel = _sizing_channel()

    def test_a_target_below_the_engine_minimum_is_declared(self) -> None:
        context = _free_context(min_raise_to_bb=9.0, max_raise_to_bb=60.0)
        window = model.raise_sizing_window(context, action="RAISE")
        self.assertEqual((window["floor_bb"], window["cap_bb"]), (9.0, 60.0))
        below = model.score_raise_sizing(
            self.channel, context, 5.0, action="RAISE", config=FAST_CONFIG, steps=STEPS
        )
        self.assertFalse(below["inside_window"])
        self.assertFalse(below["scored"])
        self.assertEqual(below["fail_closed_reason"], "TARGET_OUTSIDE_LEGAL_WINDOW")
        self.assertFalse(below["nearest_price_substituted"])
        self.assertEqual(below["legal_window"]["floor_bb"], 9.0)

    def test_a_target_beyond_the_engine_cap_is_declared(self) -> None:
        context = _free_context()
        window = model.raise_sizing_window(context, action="RAISE")
        beyond = model.score_raise_sizing(
            self.channel,
            context,
            float(window["cap_bb"]) + 1.0,
            action="RAISE",
            config=FAST_CONFIG,
            steps=STEPS,
        )
        self.assertFalse(beyond["inside_window"])
        self.assertFalse(beyond["scored"])
        self.assertEqual(beyond["fail_closed_reason"], "TARGET_OUTSIDE_LEGAL_WINDOW")
        self.assertFalse(beyond["nearest_price_substituted"])
        self.assertEqual(beyond["legal_window"]["cap_bb"], window["cap_bb"])

    def test_the_boundaries_of_the_window_stay_scored(self) -> None:
        context = _free_context(min_raise_to_bb=9.0, max_raise_to_bb=60.0)
        for target in (9.0, 60.0):
            with self.subTest(target=target):
                score = model.score_raise_sizing(
                    self.channel, context, target, action="RAISE", config=FAST_CONFIG, steps=STEPS
                )
                self.assertTrue(score["inside_window"])
                self.assertTrue(score["scored"])

    def test_generated_sizings_stay_inside_the_declared_engine_window(self) -> None:
        context = _free_context(min_raise_to_bb=9.0, max_raise_to_bb=60.0)
        generation = model.generate_raise_sizings(
            self.channel, context, action="RAISE", config=FAST_CONFIG, steps=STEPS
        )
        self.assertEqual(generation["status"], "RESOLVED")
        self.assertEqual(generation["illegal_count"], 0)
        self.assertTrue(generation["sizings_bb"])
        for sizing in generation["sizings_bb"]:
            self.assertGreaterEqual(sizing, generation["legal_window"]["floor_bb"] - 1e-9)
            self.assertLessEqual(sizing, generation["legal_window"]["cap_bb"] + 1e-9)


